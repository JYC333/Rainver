/**
 * A digest's day is a calendar date of the digest's own timezone. It is shown
 * as that date — formatted for the reader's language, never shifted into the
 * reader's timezone — beside the timezone it belongs to.
 */
export function formatDigestDate(date: string, locale: string): string {
  return new Intl.DateTimeFormat(locale, { dateStyle: 'medium', timeZone: 'UTC' }).format(new Date(`${date}T00:00:00Z`))
}

export function shiftDigestDate(date: string, days: number): string {
  const at = new Date(`${date}T00:00:00Z`)
  at.setUTCDate(at.getUTCDate() + days)
  return at.toISOString().slice(0, 10)
}

function formatInstant(iso: string, locale: string): string {
  return new Intl.DateTimeFormat(locale, { dateStyle: 'medium', timeStyle: 'short' }).format(new Date(iso))
}

function relativeFromNow(iso: string, locale: string, now: number): string {
  const seconds = Math.round((Date.parse(iso) - now) / 1000)
  const format = new Intl.RelativeTimeFormat(locale, { numeric: 'auto' })
  if (Math.abs(seconds) < 60) return format.format(seconds, 'second')
  const minutes = Math.round(seconds / 60)
  if (Math.abs(minutes) < 60) return format.format(minutes, 'minute')
  return format.format(Math.round(minutes / 60), 'hour')
}

/** Which day is shown, and stepping to the day before or after. The next day stops at the latest complete one. */
export function DigestDayNav({ date, timezone, onSelect, canGoForward }: {
  date: string
  timezone: string
  onSelect: (date: string) => void
  canGoForward: boolean
}) {
  const { t, locale } = useAppTranslation()
  return (
    <div className="flex items-center gap-2 text-xs text-muted-foreground">
      <Button variant="ghost" size="sm" type="button" aria-label={t('digest_reports.previous_day')} onClick={() => onSelect(shiftDigestDate(date, -1))}>
        <ChevronLeft className="size-4" />
      </Button>
      <span>{t('digest_reports.day_label', { date: formatDigestDate(date, locale), timezone })}</span>
      <Button variant="ghost" size="sm" type="button" aria-label={t('digest_reports.next_day')} disabled={!canGoForward} onClick={() => onSelect(shiftDigestDate(date, 1))}>
        <ChevronRight className="size-4" />
      </Button>
    </div>
  )
}

/** How the shown snapshot came to be: the day's scheduled pass, or a later backfill. */
export function DigestProvenance({ digest }: { digest: InformationDigest }) {
  const { t, locale } = useAppTranslation()
  if (digest.generation_kind === 'scheduled') return <p className="text-xs text-muted-foreground">{t('digest_reports.scheduled')}</p>
  return (
    <div className="text-xs text-muted-foreground space-y-0.5" role="note">
      <p>{t('digest_reports.backfilled', { when: formatInstant(digest.generated_at, locale) })}</p>
      <p>{t('digest_reports.backfill_note')}</p>
    </div>
  )
}

/** A day with no snapshot. Nothing is generated by looking; a backfill is an explicit action. */
export function DigestMissing({ missing, onBackfill }: {
  missing: InformationDigestMissing
  onBackfill?: (date: string) => Promise<void>
}) {
  const { t, locale } = useAppTranslation()
  const [busy, setBusy] = useState(false)
  return (
    <Card className="p-4 space-y-2">
      <p className="text-sm font-medium">{t('digest_reports.missing_title', { date: formatDigestDate(missing.digest_date, locale) })}</p>
      <p className="text-xs text-muted-foreground">{missing.explanation}</p>
      {missing.backfill_available && onBackfill && (
        <Button
          size="sm"
          variant="outline"
          type="button"
          disabled={busy}
          onClick={async () => {
            setBusy(true)
            try { await onBackfill(missing.digest_date) } finally { setBusy(false) }
          }}
        >
          {busy ? t('digest_reports.backfilling') : t('digest_reports.backfill')}
        </Button>
      )}
    </Card>
  )
}

/**
 * The reader's own Source annotation failure episodes. A countdown appears
 * only while an automatic retry is scheduled; a condition wait names the
 * condition instead, and a paused episode offers the manual retry.
 */
export function AnnotationRecoveryNotice({ spaceId }: { spaceId: string }) {
  const { t, locale } = useAppTranslation()
  const [episodes, setEpisodes] = useState<SourceAnnotationEpisode[]>([])
  const [busy, setBusy] = useState(false)
  const [now, setNow] = useState(() => Date.now())

  const load = useCallback(async () => {
    try {
      setEpisodes((await informationDigestsApi.annotationEpisodes(spaceId)).episodes)
    } catch {
      setEpisodes([])
    }
  }, [spaceId])

  useEffect(() => { void load() }, [load])
  useEffect(() => {
    if (!episodes.some(episode => episode.next_retry_at)) return
    const timer = window.setInterval(() => setNow(Date.now()), 30_000)
    return () => window.clearInterval(timer)
  }, [episodes])

  if (episodes.length === 0) return null
  return (
    <Card className="p-4 space-y-2" role="status">
      {episodes.map(episode => (
        <p key={`${episode.episode_id}:${episode.wait_reason}`} className="text-sm">
          {t(`digest_reports.annotation_${episode.wait_reason}`, {
            count: episode.affected_count,
            ...(episode.next_retry_at ? {
              relative: relativeFromNow(episode.next_retry_at, locale, now),
              when: formatInstant(episode.next_retry_at, locale),
            } : {}),
          })}
        </p>
      ))}
      <Button
        size="sm"
        variant="outline"
        type="button"
        disabled={busy}
        onClick={async () => {
          setBusy(true)
          try {
            const result = await informationDigestsApi.retryAnnotation(spaceId)
            toast.success(result.reopened > 0
              ? t('digest_reports.annotation_retry_done', { count: result.reopened })
              : t('digest_reports.annotation_retry_nothing'))
            await load()
          } catch (error) {
            toast.error(errMsg(error))
          } finally {
            setBusy(false)
          }
        }}
      >
        {busy ? t('digest_reports.annotation_retrying') : t('digest_reports.annotation_retry')}
      </Button>
    </Card>
  )
}
