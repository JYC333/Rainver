import {mkdtemp,mkdir,writeFile,readFile,rm,readdir,symlink,rename} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
const exec=promisify(execFile);
import {afterEach,beforeEach,beforeAll,expect,it} from 'vitest';
import {sweepRetiredIgnored} from '../src/workspaceIgnored.js';
let config:string,dir:string;
beforeAll(async()=>{await exec(process.execPath,[resolve('node_modules/typescript/bin/tsc'),'-p','tsconfig.build.json']);});
const now=Date.now(),old=new Date(now-31*86400_000).toISOString();
beforeEach(async()=>{config=await mkdtemp(join(tmpdir(),'ignored-sweep-'));process.env.RAINVER_HOST_CONFIG_DIR=config;dir=join(config,'task-worktrees-quarantine','location');await mkdir(dir,{recursive:true});});
afterEach(async()=>{delete process.env.RAINVER_HOST_CONFIG_DIR;await rm(config,{recursive:true,force:true});});
async function snapshot(key:string,patch:Record<string,unknown>={}){
 const base=join(dir,`${key}-preserved-ignored`);await mkdir(join(base,'files','build'),{recursive:true});
 await writeFile(join(base,'files','build','output'),'generated bytes');
 await writeFile(join(base,'manifest.json'),JSON.stringify({version:2,location_id:'location',workspace_key:key,original_root:'/unused',paths:['build'],state:'preserved',retention:'owner_review',bytes:0,retired_paths:['build'],retired_at:old,...patch}));
 return base;
}
it('isolates corrupt grants and unsafe paths while deleting later expired roots and retaining unknown bytes',async()=>{
 const broken=await snapshot('broken');await writeFile(join(broken,'manifest.json'),'{');
 const invalid=await snapshot('invalid',{retired_paths:['build','../outside']});
 const wrong=await snapshot('wrong',{location_id:'other'});
 const invalidDate=await snapshot('date',{retired_at:'invalid'});
 const linked=await snapshot('linked');await rm(join(linked,'files','build'),{recursive:true});
 const outside=join(config,'outside');await mkdir(outside);await writeFile(join(outside,'keep'),'unique');await symlink(outside,join(linked,'files','build'));
 // rm removes the authorized symlink itself, without following it.
 const good=await snapshot('good',{paths:['build','.env']});await writeFile(join(good,'files','.env'),'unique environment');
 const unknown=await snapshot('unknown');await writeFile(join(unknown,'extra'),'unlisted');
 const gone=await snapshot('gone');
 const logs:string[]=[];await sweepRetiredIgnored(config,'location',now,line=>logs.push(line));
 expect(await readFile(join(invalid,'files','build','output'),'utf8')).toBe('generated bytes');
 expect(await readFile(join(wrong,'files','build','output'),'utf8')).toBe('generated bytes');
 expect(await readFile(join(invalidDate,'files','build','output'),'utf8')).toBe('generated bytes');
 expect(await readFile(join(outside,'keep'),'utf8')).toBe('unique');
 expect(await readFile(join(good,'files','.env'),'utf8')).toBe('unique environment');
 expect(await readdir(join(good,'files'))).toEqual(['.env']);
 expect(await readFile(join(unknown,'extra'),'utf8')).toBe('unlisted');
 await expect(readdir(gone)).rejects.toMatchObject({code:'ENOENT'});
 expect(logs.join('\n')).toContain('invalid_json');expect(logs.join('\n')).toContain('workspace_ignored_manifest_invalid');
 expect(logs.join('\n')).toContain('workspace_ignored_unknown_content');
});
it('continues independent roots after a path failure and resumes after deletion before manifest progress',async()=>{
 const base=await snapshot('partial',{paths:['build','broken/cache'],retired_paths:['broken/cache','build']});
 await writeFile(join(base,'files','broken'),'blocking regular file');
 const logs:string[]=[];await sweepRetiredIgnored(config,'location',now,line=>logs.push(line));
 expect(await readdir(join(base,'files'))).toEqual(['broken']);
 expect(JSON.parse(await readFile(join(base,'manifest.json'),'utf8')).retired_paths).toEqual(['broken/cache']);
 expect(logs.join('\n')).toContain('ENOTDIR');
 await rm(join(base,'files','broken')); // Replay of a removal whose manifest write was lost.
 await sweepRetiredIgnored(config,'location',now);
 await expect(readdir(base)).rejects.toMatchObject({code:'ENOENT'});
});

it('converges beyond 10000 real snapshots over restarts, isolates corrupt grants, and cycles to newly inserted earlier names',async()=>{
 const {governIgnored}=await import('../src/workspaceIgnored.js');
 const moduleUrl=new URL('../dist/workspaceIgnored.js',import.meta.url).href;
 const childSweep=()=>exec(process.execPath,['--input-type=module','-e',`import {sweepRetiredIgnored} from ${JSON.stringify(moduleUrl)};await sweepRetiredIgnored(process.env.RAINVER_HOST_CONFIG_DIR,'location',${now});`],{env:{PATH:process.env.PATH,RAINVER_HOST_CONFIG_DIR:config}});
 for(let i=0;i<10050;i++){
  const key=`entry-${String(i).padStart(5,'0')}`;
  await snapshot(key,i%100===0?{paths:['build','.env']}:{});
  if(i%100===0)await writeFile(join(dir,`${key}-preserved-ignored`,'files','.env'),'unique');
 }
 const bad=await snapshot('entry-01001-bad');await writeFile(join(bad,'manifest.json'),'{');
 const unauthorized=await snapshot('entry-02001-unknown',{retired_paths:[]});
 const errors:string[]=[];let after:string|undefined,total=0;
 for(let n=0;n<50;n++){
  const page=await governIgnored(config,'location','list',undefined,false,undefined,{after,limit:256});
  if(!('items' in page))throw new Error('page');
  total+=page.items?.length??0;
  errors.push(...(page.errors??[]).map(e=>e.error));
  after=page.next??undefined;if(!after)break;
 }
 expect(total).toBe(10051);expect(errors).toContain('invalid_json');
 const sweep=(await import('../src/workspaceIgnored.js')).sweepRetiredIgnored;
 await sweep(config,'location',now);
 // A cursor before this addition must continue to the tail, not restart.
 const early=await snapshot('aaa-added');
 await rm(join(dir,'entry-01005-preserved-ignored'),{recursive:true});
 let passes=0;
 // Restart passes follow persisted progress, rather than assuming a disk throughput.
 for(;passes<256;passes++){
  await childSweep();
  const {access}=await import('node:fs/promises');
  if(!await access(join(dir,'entry-10049-preserved-ignored')).then(()=>true,()=>false)&&!await access(early).then(()=>true,()=>false))break;
 }
 console.info(`convergence: 10050 snapshots, ${passes+1} restart passes; tail and early additions absent`);
 await expect(readdir(join(dir,'entry-10049-preserved-ignored'))).rejects.toMatchObject({code:'ENOENT'});
 expect(await readFile(join(dir,'entry-04100-preserved-ignored','files','.env'),'utf8')).toBe('unique');
 expect(await readFile(join(unauthorized,'files','build','output'),'utf8')).toBe('generated bytes');
 // The end of a cycle clears only its scheduling frontier. Earlier additions
 // get the following page; invalid JSON remains available for owner recovery.
 await sweep(config,'location',now);
 await expect(readdir(early)).rejects.toMatchObject({code:'ENOENT'});
 expect(await readFile(join(bad,'manifest.json'),'utf8')).toBe('{');
});
it('retries a page after durable cursor failure and safely restarts a damaged scheduling cursor',async()=>{
 const {setDurableIoForTest}=await import('../src/durableFile.js');
 const {createHash}=await import('node:crypto');
 for(let i=0;i<300;i++)await snapshot(`fault-${String(i).padStart(4,'0')}`);
 const unique=await snapshot('aaa-unknown',{retired_paths:[]});
 let failed=false;
 const restore=setDurableIoForTest({async rename(from,to){if(to.includes('workspace-sweeps')&&!failed){failed=true;throw new Error('cursor fault');}await rename(from,to);}});
 try{await expect(sweepRetiredIgnored(config,'location',now)).rejects.toThrow('cursor fault');}finally{restore();}
 expect(failed).toBe(true);
 for(let n=0;n<8;n++)await sweepRetiredIgnored(config,'location',now);
 await expect(readdir(join(dir,'fault-0299-preserved-ignored'))).rejects.toMatchObject({code:'ENOENT'});
 const state=join(config,'workspace-sweeps',createHash('sha256').update('ignored-location\0'+dir).digest('hex')+'.json');
 await mkdir(join(config,'workspace-sweeps'),{recursive:true});await writeFile(state,'{');
 await snapshot('late-after-fault');
 const logs:string[]=[];await sweepRetiredIgnored(config,'location',now,s=>logs.push(s));
 await expect(readdir(join(dir,'late-after-fault-preserved-ignored'))).rejects.toMatchObject({code:'ENOENT'});
 expect(logs.join('\n')).toContain('restarting invalid scheduling cursor');
 expect(await readFile(join(unique,'files','build','output'),'utf8')).toBe('generated bytes');
});
