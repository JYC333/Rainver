const db = useTestDatabase(import.meta.filename);
let space: string, owner: string, project: string, thread: string, app: FastifyInstance;
const identity = () => ({ spaceId: space, userId: owner });
const url = () => `/api/v1/projects/${project}`;
beforeEach(async () => {
    await resetTables(db.pool, ['spaces', 'users'], { cascade: true });
    space = randomUUID();
    owner = randomUUID();
    project = randomUUID();
    await seedSpaceOwnerProject(db.pool, { space, owner, project, spaceType: 'household' });
    thread = String((await new InquiryThreadService(db.pool).createThread(identity(), project, { kind: 'question', statement: 'Why does import fail?' })).id);
    __setAuthIdentityForTests(identity());
    app = buildModuleServer(loadConfig({ SERVER_DATABASE_URL: db.connectionUri, RAINVER_HOME: '/tmp/rainver-p5-tests' }), [inquiryModule, projectResearchModule,readerModule]);
});
afterEach(async () => { await app?.close(); __setAuthIdentityForTests(null); });
it('reads paged problem summaries without mutation and preserves definition boundaries in canonical version snapshots', async () => {
    const before = await db.pool.query('SELECT count(*)::int AS n FROM inquiry_thread_steps');
    const response = await app.inject({ method: 'GET', url: url() + '/inquiry/workspace-threads' });
    expect(response.statusCode, response.body).toBe(200);
    expect(response.json().items[0].id).toBe(thread);
    expect((await app.inject({ method: 'GET', url: url() + '/inquiry/workspace-access' })).json()).toEqual({ can_write: true });
    expect((await db.pool.query('SELECT count(*)::int AS n FROM inquiry_thread_steps')).rows).toEqual(before.rows);
    const iterations = new InquiryIterationService(db.pool);
    await iterations.reviseDefinition(identity(), project, thread, { revision_kind: 'semantic_change', structure_action: 'narrow', new_statement: 'Why does CSV import fail?', new_scope_boundary: 'Local CSV only', new_resolution_criteria: 'Reproducible cause', impact_note: 'Scope is explicit' });
    const detail = await new InquiryThreadService(db.pool).getThread(identity(), project, thread);
    expect(detail.scope_boundary).toBe('Local CSV only');
    const snapshot = (await db.pool.query('SELECT state_snapshot_json FROM inquiry_thread_revisions WHERE thread_id=$1 ORDER BY version DESC LIMIT 1', [thread])).rows[0];
    expect(snapshot.state_snapshot_json.scope_boundary).toBe('Local CSV only');
    await expect(iterations.reviseDefinition(identity(), project, thread, { revision_kind: 'wording_only', new_statement: 'Other wording', new_scope_boundary: 'New scope' })).rejects.toMatchObject({ statusCode: 422 });
    await new InquiryIterationService(db.pool).updateWork(identity(), project, thread, { answer_state: 'answered' });
    expect((await new InquiryThreadService(db.pool).getThread(identity(), project, thread)).question_state).toMatchObject({ answer_state: 'open' });
    expect((await new InquiryProblemEngineService(db.pool).projection(identity(), project, thread)).can_write).toBe(true);
});
it('paginates all matching readable Threads and refuses invalid filters without disclosing private judgment', async () => {
    const member = randomUUID();
    await seedSpaceMember(db.pool, { space, user: member, role: 'member' });
    await db.pool.query(`INSERT INTO project_members(id,space_id,project_id,user_id,role,status,created_at,updated_at) VALUES($1,$2,$3,$4,'member','active',now(),now())`, [randomUUID(), space, project, member]);
    await db.pool.query("UPDATE inquiry_question_states SET current_answer_summary='PRIVATE JUDGMENT' WHERE thread_id=$1", [thread]);
    await db.pool.query("UPDATE space_objects SET visibility='private' WHERE id=$1", [thread]);
    __setAuthIdentityForTests({ spaceId: space, userId: member });
    const memberRead = await app.inject({ method: 'GET', url: url() + '/inquiry/workspace-threads?status=all' });
    expect(memberRead.statusCode).toBe(200);
    expect(memberRead.body).not.toContain('PRIVATE JUDGMENT');
    __setAuthIdentityForTests(identity());
    for (let i = 0; i < 51; i++)
        await new InquiryThreadService(db.pool).createThread(identity(), project, { kind: 'question', statement: `Page item ${i}` });
    const a = (await app.inject({ method: 'GET', url: url() + '/inquiry/workspace-threads?q=Page' })).json();
    expect(a.items).toHaveLength(50);
    expect(a.next_cursor).toBeTruthy();
    const b = (await app.inject({ method: 'GET', url: url() + `/inquiry/workspace-threads?q=Page&after_thread_id=${a.next_cursor}` })).json();
    expect(b.items).toHaveLength(1);
    expect(a.items.some((x: {
        id: string;
    }) => x.id === b.items[0].id)).toBe(false);
    expect((await app.inject({ method: 'GET', url: url() + '/inquiry/workspace-threads?status=invalid' })).statusCode).toBe(422);
});
it('admits HTTP research through existing bounded binding and exposes scoped operations without starting work on reads', async () => {
    const payload = { thread_id: thread, idempotency_key: 'one', intent_note: 'Find cause' };
    const start = await app.inject({ method: 'POST', url: url() + '/research/acquisitions', payload });
    expect(start.statusCode, start.body).toBe(202);
    const id = start.json().operation_id;
    expect(id).toBeTruthy();
    const replay = await app.inject({ method: 'POST', url: url() + '/research/acquisitions', payload });
    expect(replay.statusCode, replay.body).toBe(202);
    expect(replay.json().operation_id).toBe(id);
    const list = await app.inject({ method: 'GET', url: url() + `/inquiry/threads/${thread}/research-operations` });
    expect(list.statusCode, list.body).toBe(200);
    expect(list.json().items[0]).toMatchObject({ id, progress_json: { workflow_id: expect.any(String) } });
    const other = String((await new InquiryThreadService(db.pool).createThread(identity(), project, { kind: 'question', statement: 'Another question' })).id);
    expect((await app.inject({ method: 'GET', url: url() + `/inquiry/threads/${other}/research-operations` })).json().items).toHaveLength(0);
});
it('withholds bound report titles/bodies after Source withdrawal while scoped operation status and stopping remain', async () => {
    const a = await new ResearchAcquisitionService(db.pool).startAcquisition(identity(), project, { threadId: thread, requestKey: 'report', originRoomId: null, originSessionId: null });
    const operation = a.operation_id!, row = (await db.pool.query(`SELECT research_call_json FROM project_operations WHERE id=$1`, [operation])).rows[0];
    const connection = randomUUID(), channel = randomUUID();
    await seedArxivSourceChain(db.pool, { space, owner, connection, connector: randomUUID(), channel, now: new Date().toISOString() });
    const run = randomUUID(), artifact = randomUUID(), report = randomUUID();
    await seedRun(db.pool, { id: run, space, owner, agent: randomUUID(), version: randomUUID() });
    await db.pool.query(`INSERT INTO artifacts(id,space_id,artifact_type,title,export_formats_json,owner_user_id,visibility,created_at,updated_at) VALUES($1,$2,'report','SECRET REPORT','[]'::jsonb,$3,'space_shared',now(),now())`, [artifact, space, owner]);
    await db.pool.query(`INSERT INTO project_research_reports(id,space_id,project_id,workflow_id,operation_id,synthesis_run_id,run_kind,research_question,research_question_version,content_json,reader_document_json,normalized_text,content_hash,archive_artifact_id,created_at,updated_at) VALUES($1,$2,$3,$4,$5,$6,'baseline','SECRET REPORT',1,'{}'::jsonb,'{}'::jsonb,'SECRET BODY',$7,$8,now(),now())`, [report, space, project, row.research_call_json.workflow_id, operation, run, '0'.repeat(64), artifact]);
    expect(await new ProjectResearchReportRepository(db.pool).list(identity(), project)).toHaveLength(1);
    expect(await new PgReaderRepository(db.pool,loadConfig({SERVER_DATABASE_URL:db.connectionUri,RAINVER_HOME:'/tmp/rainver-p5-tests'})).getDocument(identity(),'research_report',report)).toMatchObject({title:'SECRET REPORT',plain_text:'SECRET BODY'});
    const material = await seedRelevantCorpusItem(db.pool, { space, project, owner });
    await db.pool.query(`UPDATE source_items SET connection_id=$2 WHERE id=$1`, [material.sourceItemId, connection]);
    await db.pool.query(`UPDATE project_operations SET progress_json=progress_json||jsonb_build_object('channel_ids',jsonb_build_array($2::text),'source_item_ids',jsonb_build_array($3::text)) WHERE id=$1`, [operation, channel, material.sourceItemId]);
    await db.pool.query(`UPDATE source_connections SET status='archived' WHERE id=$1`, [connection]);
    expect(await new ProjectResearchReportRepository(db.pool).list(identity(), project)).toHaveLength(0);
    const detail = await app.inject({ method: 'GET', url: url() + `/research/reports/${report}` });
    expect(detail.statusCode, detail.body).toBe(404);
    expect(detail.body).not.toContain('SECRET');
    expect((await app.inject({method:'GET',url:`/api/v1/reader/documents/research_report/${report}`})).statusCode).toBe(404);
    await expect(new PgReaderRepository(db.pool,loadConfig({SERVER_DATABASE_URL:db.connectionUri,RAINVER_HOME:'/tmp/rainver-p5-tests'})).getDocument(identity(),'research_report',report)).rejects.toMatchObject({statusCode:404});
    await expect(assertDocumentReadable(db.pool,identity(),'research_report',report)).rejects.toMatchObject({statusCode:404});
    const list = await app.inject({ method: 'GET', url: url() + `/inquiry/threads/${thread}/research-operations` });
    expect(list.statusCode, list.body).toBe(200);
    expect(list.json().items[0]).toMatchObject({ id: operation, content_withheld: true, stop_ref: { operation_id: operation } });
    expect(list.body).not.toContain('SECRET');
    expect(list.body).not.toContain(channel);
    const running=await listRunningProjectOperations(db.pool,space,project,owner);expect(JSON.stringify(running)).not.toContain('SECRET');expect(running[0]!.progress_json.content_withheld).toBe(true);
    await db.pool.query(`UPDATE project_operations SET title='SECRET PENDING',status='waiting_review' WHERE id=$1`,[operation]);registerBuiltInAttentionAdapters();const attention=await new ProjectAttentionService(db.pool).listAttentionItems(identity(),project);expect(JSON.stringify(attention)).not.toContain('SECRET');
    const cancel = await app.inject({ method: 'POST', url: url() + `/research/operations/${operation}/cancel`, payload: {} });
    expect(cancel.statusCode, cancel.body).toBe(200);
});
