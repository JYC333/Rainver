// vector extension. The host-thread tool-field widening is inside this frozen
// baseline. Databases from the preceding epoch must be recreated, not upgraded.
const FROZEN_BASELINE_SHA256 = "d1303347cf8ecc2af391ddc521823d902c57e0f5fe208c21ccb597c4b24ec946";

