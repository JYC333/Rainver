  it("brings forward a database the previous release wrote, rows and all", async () => {
    if (!db.available) return;
    // Production runs the baseline alone. Apply exactly that, write rows in
    // the shapes the previous release wrote them, then apply the rest of the
    // chain: every migration must succeed on them and give them the new
    // meaning, without any repair of old data.
    await resetSchema(db.pool);
    const releaseDir = mkdtempSync(join(tmpdir(), "rainver-release-chain-"));
    try {
      copyFileSync(join(MIGRATIONS_DIR, "0000_baseline.sql"), join(releaseDir, "0000_baseline.sql"));
      await migrate(db.pool, releaseDir);
    } finally {
      rmSync(releaseDir, { recursive: true, force: true });
    }

    const client = await db.pool.connect();
    try {
      // Foreign keys are not what this test is about; the rows only need the
      // shapes the release stored.
      await client.query("SET session_replication_role = replica");
      await client.query(
        `INSERT INTO information_digests (id, space_id, owner_user_id, digest_type, digest_date, created_at, updated_at)
         VALUES ('digest-old', 'space-old', 'user-old', 'personal', '2026-09-30', now(), now())`,
      );
      await client.query(
        `INSERT INTO run_finalizations (id, space_id, run_id, attempt_number, status, finalized_at, created_at, metadata_json)
         VALUES ('final-gated', 'space-old', 'run-1', 1, 'completed', '2026-10-01T10:00:00Z', '2026-10-01T10:00:00Z',
                 '{"completion_gate_committed": true, "completion_gate_committed_at": "2026-10-01T10:00:05Z"}'::jsonb),
                ('final-ungated', 'space-old', 'run-2', 1, 'completed', '2026-10-02T10:00:00Z', '2026-10-02T10:00:00Z', NULL),
                ('final-failed', 'space-old', 'run-3', 1, 'failed', '2026-10-03T10:00:00Z', '2026-10-03T10:00:00Z', NULL)`,
      );
      // The previous release let a Space owner promote a version to system
      // scope without clearing its Space.
      await client.query(
        `INSERT INTO evolvable_asset_versions (id, asset_id, space_id, scope_type, scope_id, version, status, source, created_at, updated_at)
         VALUES ('version-old', 'asset-old', 'space-old', 'system', NULL, 1, 'approved', 'user_authored', now(), now())`,
      );
      // Subscriptions in the release's shape: no subscription period recorded.
      // The window the migration opens references a real channel and person.
      await client.query(
        `INSERT INTO users (id, display_name, status, created_at, updated_at, email, registration_source)
         VALUES ('user-old', 'Old reader', 'active', now(), now(), 'old-reader@test.invalid', 'system')`,
      );
      await client.query(
        `INSERT INTO source_channels (
           id, space_id, source_connection_id, created_by_user_id, name, channel_type, endpoint_url,
           query_json, provider_query_json, query_fingerprint, status, fetch_frequency, schedule_rule_json, created_at, updated_at
         ) VALUES ('channel-old', 'space-old', 'connection-old', 'user-old', 'Feed', 'feed', 'https://example.com/rss',
           '{}'::jsonb, '{}'::jsonb, 'fingerprint-old', 'active', 'daily', '{"frequency":"daily","hour":0,"minute":0}'::jsonb, now(), now())`,
      );
      await client.query(
        `INSERT INTO source_channel_user_subscriptions (id, space_id, source_channel_id, user_id, status, library_enabled, digest_enabled, created_at, updated_at)
         VALUES ('sub-live', 'space-old', 'channel-old', 'user-old', 'subscribed', true, true, '2026-09-01T08:00:00Z', '2026-09-01T08:00:00Z'),
                ('sub-left', 'space-old', 'channel-old', 'user-gone', 'muted', true, true, '2026-09-02T08:00:00Z', '2026-09-03T08:00:00Z'),
                ('sub-declined', 'space-old', 'channel-old', 'user-other', 'dismissed', true, true, '2026-09-04T08:00:00Z', '2026-09-04T08:00:00Z')`,
      );
      await client.query("RESET session_replication_role");
    } finally {
      client.release();
    }

    await migrate(db.pool, MIGRATIONS_DIR);

    const digest = await db.pool.query<{ period_start_utc: Date; period_end_utc: Date; timezone: string }>(
      `SELECT period_start_utc, period_end_utc, timezone FROM information_digests WHERE id = 'digest-old'`,
    );
    expect(digest.rows[0]).toMatchObject({
      timezone: "UTC",
      period_start_utc: new Date("2026-09-30T00:00:00Z"),
      period_end_utc: new Date("2026-10-01T00:00:00Z"),
    });

    // A finalization the release completed is settled; the sweep does not
    // replay months of reconcilers.
    const settled = await db.pool.query<{ id: string; settled_at: Date | null }>(
      `SELECT id, settled_at FROM run_finalizations ORDER BY id`,
    );
    expect(Object.fromEntries(settled.rows.map((row) => [row.id, row.settled_at?.toISOString() ?? null]))).toEqual({
      "final-failed": null,
      "final-gated": "2026-10-01T10:00:05.000Z",
      "final-ungated": "2026-10-02T10:00:00.000Z",
    });

    // The old system-scope row survives; the placement rule binds new writes.
    await expect(db.pool.query(
      `UPDATE evolvable_asset_versions SET updated_at = now() WHERE id = 'version-old'`,
    )).rejects.toMatchObject({ constraint: "ck_evolvable_asset_versions_system_scope_placement" });
    const notValid = await db.pool.query<{ convalidated: boolean }>(
      `SELECT convalidated FROM pg_constraint WHERE conname = 'ck_evolvable_asset_versions_system_scope_placement'`,
    );
    expect(notValid.rows[0]?.convalidated).toBe(false);

    // A live subscription has an open period from when it was recorded; the
    // others (left, declined) have none. Leaving it then closes that period
    // without any constraint in the way.
    const windows = await db.pool.query<{ user_id: string; subscribed_at: Date; unsubscribed_at: Date | null }>(
      `SELECT user_id, subscribed_at, unsubscribed_at FROM source_channel_subscription_windows ORDER BY user_id`,
    );
    expect(windows.rows).toEqual([
      { user_id: "user-old", subscribed_at: new Date("2026-09-01T08:00:00Z"), unsubscribed_at: null },
    ]);
    const client2 = await db.pool.connect();
    try {
      await client2.query("SET session_replication_role = replica");
      await client2.query(`UPDATE source_channel_user_subscriptions SET status = 'muted', updated_at = now() WHERE id = 'sub-live'`);
      await closeSubscriptionWindow(client2, { spaceId: "space-old", channelId: "channel-old", userId: "user-old", at: "2026-10-05T08:00:00Z" });
      await client2.query("RESET session_replication_role");
    } finally {
      client2.release();
    }
    const closed = await db.pool.query<{ unsubscribed_at: Date }>(
      `SELECT unsubscribed_at FROM source_channel_subscription_windows WHERE user_id = 'user-old'`,
    );
    expect(closed.rows[0]!.unsubscribed_at).toEqual(new Date("2026-10-05T08:00:00Z"));
  }, 180_000);

